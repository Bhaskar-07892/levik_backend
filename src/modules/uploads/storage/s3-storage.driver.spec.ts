import { GetObjectCommand, PutObjectCommand, type S3Client } from '@aws-sdk/client-s3';
import { NotFoundException } from '@nestjs/common';
import { S3StorageDriver } from './s3-storage.driver.js';

const settings = {
  endpoint: 'https://account-id.r2.cloudflarestorage.com',
  region: 'auto',
  bucket: 'levik-uploads',
  accessKeyId: 'test-access-key',
  secretAccessKey: 'test-secret-key',
  forcePathStyle: false,
};
const KEY = 'shop-photo_0b6b5a3e-8f0e-4a8e-9c7e-0d6f3c1a2b4c.webp';

describe('S3StorageDriver', () => {
  it('stores objects under a purpose folder with their content type', async () => {
    const send = vi.fn().mockResolvedValue({});
    const driver = new S3StorageDriver(settings, { send } as unknown as S3Client);
    await driver.put(KEY, Buffer.from('img'), 'image/webp');
    const command = send.mock.calls[0][0] as PutObjectCommand;
    expect(command).toBeInstanceOf(PutObjectCommand);
    expect(command.input).toMatchObject({ Bucket: 'levik-uploads', Key: `shop-photo/${KEY}`, ContentType: 'image/webp' });
  });

  it('reads objects from the same path', async () => {
    const send = vi.fn().mockResolvedValue({ Body: 'stream' });
    const driver = new S3StorageDriver(settings, { send } as unknown as S3Client);
    expect(await driver.get(KEY)).toBe('stream');
    const command = send.mock.calls[0][0] as GetObjectCommand;
    expect(command.input).toEqual({ Bucket: 'levik-uploads', Key: `shop-photo/${KEY}` });
  });

  it('presigns a GET for the object without calling the bucket', async () => {
    const driver = new S3StorageDriver(settings);
    const url = new URL(await driver.signedUrl(KEY, 600));
    expect(url.host).toBe('levik-uploads.account-id.r2.cloudflarestorage.com');
    expect(url.pathname).toBe(`/shop-photo/${KEY}`);
    expect(url.searchParams.get('X-Amz-Expires')).toBe('600');
    expect(url.searchParams.get('X-Amz-Signature')).toMatch(/^[0-9a-f]{64}$/);
  });

  it('refuses keys that were not generated by the API', async () => {
    const send = vi.fn();
    const driver = new S3StorageDriver(settings, { send } as unknown as S3Client);
    await expect(driver.get('../../etc/passwd')).rejects.toBeInstanceOf(NotFoundException);
    await expect(driver.put('scan-photo/other.jpg', Buffer.from(''), 'image/jpeg')).rejects.toBeInstanceOf(NotFoundException);
    expect(send).not.toHaveBeenCalled();
  });
});
